import { NextRequest, NextResponse } from 'next/server'
import { createAdminClient } from '@/lib/supabase/server'
import { generateDarazListingContent, AiGenerationError } from '@/lib/daraz/ai-generate-service'

export const dynamic = 'force-dynamic'
export const maxDuration = 60

const MAX_ATTEMPTS = 5
const BACKOFF_MINUTES = [2, 5, 10, 20, 30]
const COOLDOWN_MS = 6000 // 6-second gap between items to protect free-tier RPM

function sleep(ms: number) {
    return new Promise(resolve => setTimeout(resolve, ms))
}

function mapPerStoreFields(
    data: {
        titles?: Record<string, string>
        descriptions?: Record<string, string>
        highlights_per_store?: Record<string, string[]>
        description?: string
        highlights?: string[]
    },
    targetStoreIds: string[],
    storeMap: Map<string, string>,
    fallbackName: string
) {
    const newTitles: Record<string, string> = {}
    const newDescriptions: Record<string, string> = {}
    const newHighlights: Record<string, string[]> = {}

    const titleValues = Object.values(data.titles || {}).filter((v): v is string => typeof v === 'string' && v.trim().length > 0)
    const descValues = Object.values(data.descriptions || {}).filter((v): v is string => typeof v === 'string' && v.trim().length > 0)
    const hlValues = Object.values(data.highlights_per_store || {}).filter((v): v is string[] => Array.isArray(v) && v.length > 0)

    targetStoreIds.forEach((storeId, idx) => {
        const storeName = storeMap.get(storeId) || storeId

        // Title match by exact store name, case-insensitive, or positional fallback
        const exactTitle = data.titles?.[storeName]
        const ciTitleKey = !exactTitle && data.titles
            ? Object.keys(data.titles).find(k => k.toLowerCase() === storeName.toLowerCase())
            : undefined
        newTitles[storeId] = exactTitle || (ciTitleKey ? data.titles![ciTitleKey] : '') || titleValues[idx] || titleValues[0] || fallbackName

        // Description per store
        const exactDesc = data.descriptions?.[storeName]
        const ciDescKey = !exactDesc && data.descriptions
            ? Object.keys(data.descriptions).find(k => k.toLowerCase() === storeName.toLowerCase())
            : undefined
        newDescriptions[storeId] = exactDesc || (ciDescKey ? data.descriptions![ciDescKey] : '') || descValues[idx] || data.description || ''

        // Highlights per store
        const exactHl = data.highlights_per_store?.[storeName]
        const ciHlKey = !exactHl && data.highlights_per_store
            ? Object.keys(data.highlights_per_store).find(k => k.toLowerCase() === storeName.toLowerCase())
            : undefined
        newHighlights[storeId] = exactHl || (ciHlKey ? data.highlights_per_store![ciHlKey] : undefined) || hlValues[idx] || data.highlights || []
    })

    return { newTitles, newDescriptions, newHighlights }
}

export async function GET(request: NextRequest) {
    const startTime = Date.now()

    // ── Authorization: require CRON_SECRET ──────────────────────────────────
    const cronSecret = process.env.CRON_SECRET
    if (cronSecret) {
        const authHeader = request.headers.get('x-cron-secret')
        const querySecret = request.nextUrl.searchParams.get('secret')
        if (authHeader !== cronSecret && querySecret !== cronSecret) {
            return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
        }
    }

    try {
        const supabase = await createAdminClient()

        // ── Check Global Auto-AI ON/OFF toggle ──────────────────────────────
        const { data: aiRow, error: settingsErr } = await supabase
            .from('app_settings')
            .select('value')
            .eq('key', 'daraz_ai_settings')
            .maybeSingle()

        if (settingsErr) {
            console.warn('[AutoGenerateDrafts] Settings fetch warning:', settingsErr.message)
            return NextResponse.json({
                success: false,
                skipped: true,
                reason: 'Database temporarily unavailable — will retry next run',
                elapsed_ms: Date.now() - startTime
            }, { status: 200 })
        }

        const autoAiEnabled = aiRow?.value?.autoAiEnabled !== false
        if (!autoAiEnabled) {
            return NextResponse.json({
                success: true,
                skipped: true,
                reason: 'Auto-AI is turned OFF globally',
                processed: 0,
                elapsed_ms: Date.now() - startTime
            })
        }

        // ── Recover any stuck 'generating' drafts older than 10 minutes ─────
        const tenMinAgoIso = new Date(Date.now() - 10 * 60 * 1000).toISOString()
        await supabase
            .from('daraz_draft_listings')
            .update({
                status: 'draft',
                auto_ai_scheduled_at: new Date(Date.now() + 2 * 60 * 1000).toISOString(),
            })
            .eq('status', 'generating')
            .lt('updated_at', tenMinAgoIso)

        // ── Pick a small safe batch (default 2, max 3) of due drafts ────────
        const limitParam = parseInt(request.nextUrl.searchParams.get('limit') || '2', 10)
        const limit = Math.max(1, Math.min(3, Number.isFinite(limitParam) ? limitParam : 2))
        const nowIso = new Date().toISOString()

        const { data: dueDrafts, error: queueErr } = await supabase
            .from('daraz_draft_listings')
            .select('*')
            .eq('status', 'draft')
            .not('auto_ai_scheduled_at', 'is', null)
            .lte('auto_ai_scheduled_at', nowIso)
            .lt('auto_ai_attempts', MAX_ATTEMPTS)
            .order('auto_ai_scheduled_at', { ascending: true })
            .limit(limit)

        if (queueErr) {
            console.warn('[AutoGenerateDrafts] Queue fetch error:', queueErr.message)
            return NextResponse.json({
                success: false,
                skipped: true,
                reason: queueErr.message,
                elapsed_ms: Date.now() - startTime
            }, { status: 200 })
        }

        if (!dueDrafts || dueDrafts.length === 0) {
            return NextResponse.json({
                success: true,
                processed: 0,
                remaining_due: 0,
                elapsed_ms: Date.now() - startTime
            })
        }

        // Load active Daraz stores for store-name mapping
        const { data: stores } = await supabase
            .from('online_stores')
            .select('id, seller_account')
            .eq('is_active', true)

        const storeMap = new Map<string, string>()
        ;(stores || []).forEach(s => storeMap.set(s.id, s.seller_account || s.id))
        const defaultStoreId = stores?.[0]?.id

        let processed = 0
        let rescheduled = 0
        let failed = 0
        let rateLimitedStop = false

        for (let i = 0; i < dueDrafts.length; i++) {
            // Leave safety buffer before Vercel 60s maxDuration
            if (Date.now() - startTime > 45_000) {
                break
            }

            const draft = dueDrafts[i]

            // ── Atomic claim: only proceed if still 'draft' ─────────────────
            const { data: claimed, error: claimErr } = await supabase
                .from('daraz_draft_listings')
                .update({ status: 'generating', updated_at: new Date().toISOString() })
                .eq('id', draft.id)
                .eq('status', 'draft')
                .select('*')
                .maybeSingle()

            if (claimErr || !claimed) {
                continue // Already claimed by another tick or manual click
            }

            // Skip if already has title + description + highlights
            const alreadyGenerated =
                Boolean(claimed.title && claimed.title.trim()) &&
                Boolean(claimed.description && claimed.description.trim()) &&
                Array.isArray(claimed.highlights) && claimed.highlights.length > 0

            if (alreadyGenerated) {
                await supabase
                    .from('daraz_draft_listings')
                    .update({ status: 'generated', auto_ai_scheduled_at: null })
                    .eq('id', claimed.id)
                continue
            }

            const images: string[] = Array.isArray(claimed.images) ? claimed.images : []
            const hasImage = images.length > 0
            const rawName = (claimed.raw_name || '').trim()
            const isGenericName = !rawName || rawName.startsWith('[Image Only]') || rawName.startsWith('[Link') || rawName === 'Untitled Draft'
            const effectiveName = !isGenericName ? rawName : (hasImage ? 'Product from uploaded image' : '')

            if (!effectiveName && !hasImage) {
                await supabase
                    .from('daraz_draft_listings')
                    .update({ status: 'draft', auto_ai_scheduled_at: null })
                    .eq('id', claimed.id)
                continue
            }

            const targetStores: string[] =
                Array.isArray(claimed.target_stores) && claimed.target_stores.length > 0
                    ? claimed.target_stores
                    : (defaultStoreId ? [defaultStoreId] : [])

            const storeNames = targetStores.map(id => storeMap.get(id) || id)

            try {
                const aiResult = await generateDarazListingContent({
                    productName: effectiveName,
                    price: claimed.price || 500,
                    imageUrl: images[0] || null,
                    storeNames: storeNames.length > 0 ? storeNames : ['Default Store'],
                    categoryPath: claimed.category_path || 'General',
                })

                const { newTitles, newDescriptions, newHighlights } = mapPerStoreFields(
                    aiResult,
                    targetStores,
                    storeMap,
                    effectiveName
                )

                const primaryTitle = Object.values(newTitles)[0] || Object.values(aiResult.titles || {})[0] || effectiveName
                const resolvedCategoryId = aiResult.category_id || claimed.category_id || null
                const resolvedCategoryPath = aiResult.category_suggestion || claimed.category_path || null

                const mergedAttributes = {
                    ...(claimed.attributes || {}),
                    ...(aiResult.attributes || {}),
                    brand: 'No Brand',
                    descriptions_per_store: newDescriptions,
                    highlights_per_store: newHighlights,
                    draft_type: resolvedCategoryId ? 'ready' : (claimed.attributes?.draft_type || 'pending'),
                    auto_ai_generated_at: new Date().toISOString(),
                    auto_ai_provider: aiResult.usedProvider,
                }

                await supabase
                    .from('daraz_draft_listings')
                    .update({
                        title: primaryTitle,
                        titles_per_store: newTitles,
                        description: aiResult.description || '',
                        highlights: aiResult.highlights || [],
                        category_id: resolvedCategoryId,
                        category_path: resolvedCategoryPath,
                        attributes: mergedAttributes,
                        target_stores: targetStores,
                        status: 'generated',
                        error: null,
                        auto_ai_scheduled_at: null,
                        updated_at: new Date().toISOString(),
                    })
                    .eq('id', claimed.id)

                processed += 1
            } catch (err: unknown) {
                const errMsg = err instanceof Error ? err.message : 'Unknown error'
                const attempts = (claimed.auto_ai_attempts || 0) + 1
                const isRateLimited = err instanceof AiGenerationError && err.isRateLimited
                const shouldRetry = attempts < MAX_ATTEMPTS

                if (shouldRetry) {
                    const backoffMin = BACKOFF_MINUTES[Math.min(attempts - 1, BACKOFF_MINUTES.length - 1)]
                    const nextRetryIso = new Date(Date.now() + backoffMin * 60 * 1000).toISOString()

                    await supabase
                        .from('daraz_draft_listings')
                        .update({
                            status: 'draft',
                            auto_ai_attempts: attempts,
                            auto_ai_scheduled_at: nextRetryIso,
                            error: `Auto-AI retry ${attempts}/${MAX_ATTEMPTS} scheduled (+${backoffMin}m): ${errMsg}`,
                            updated_at: new Date().toISOString(),
                        })
                        .eq('id', claimed.id)

                    rescheduled += 1
                } else {
                    await supabase
                        .from('daraz_draft_listings')
                        .update({
                            status: 'failed',
                            auto_ai_attempts: attempts,
                            auto_ai_scheduled_at: null,
                            error: `Auto-AI failed after ${MAX_ATTEMPTS} attempts: ${errMsg}`,
                            updated_at: new Date().toISOString(),
                        })
                        .eq('id', claimed.id)

                    failed += 1
                }

                // If all keys hit rate limit, pause remaining items in this tick so we don't hammer the API
                if (isRateLimited) {
                    rateLimitedStop = true
                    break
                }
            }

            // Cooldown pause between items in the same cron run
            if (i < dueDrafts.length - 1 && Date.now() - startTime < 38_000) {
                await sleep(COOLDOWN_MS)
            }
        }

        return NextResponse.json({
            success: true,
            processed,
            rescheduled,
            failed,
            rate_limited_stop: rateLimitedStop,
            elapsed_ms: Date.now() - startTime,
        })
    } catch (err: unknown) {
        const errMsg = err instanceof Error ? err.message : 'Unknown error'
        console.error('[AutoGenerateDrafts] Critical error:', errMsg)
        return NextResponse.json({
            success: false,
            skipped: true,
            reason: errMsg,
            elapsed_ms: Date.now() - startTime
        }, { status: 200 }) // Return 200 so cron-job.org doesn't auto-disable on transient outages
    }
}

export async function POST(request: NextRequest) {
    return GET(request)
}
